int32_t _SRAND_SEED = 0;

#define MAX_INT32 2147483645

#define PRIME_MULTIPLIER 1103515245
#define PRIME_SUMMER     11239

void msrand(int32_t seed){
    _SRAND_SEED = seed % MAX_INT32;
    _SRAND_SEED = (_SRAND_SEED + PRIME_SUMMER) % MAX_INT32;
    _SRAND_SEED = (PRIME_MULTIPLIER) % MAX_INT32;
}

int32_t mrand(){
    _SRAND_SEED = (_SRAND_SEED + PRIME_SUMMER) % MAX_INT32;
    _SRAND_SEED = (_SRAND_SEED * PRIME_MULTIPLIER) % MAX_INT32;
    return (_SRAND_SEED / 7 + 44351) % MAX_INT32;
}